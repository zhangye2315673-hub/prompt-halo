// Render the real source/package in an offscreen Electron window. Never show/focus it.
const {app,BrowserWindow,ipcMain}=require('electron');
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),os=require('node:os');
const out=fs.mkdtempSync(path.join(os.tmpdir(),'halo-neon-'));
app.setPath('userData',path.join(out,'profile'));
const root=process.env.HALO_RENDER_ROOT||path.join(__dirname,'..');
const delay=ms=>new Promise(r=>setTimeout(r,ms));
let w,inserts=0;
app.whenReady().then(async()=>{
 ipcMain.handle('test:close',()=>w.webContents.send('test:hide'));
 ipcMain.handle('test:keyboard',()=>({ok:true}));
 ipcMain.handle('test:insert',()=>{inserts++;return {ok:false,reason:'isolated renderer check'};});
 w=new BrowserWindow({show:false,width:860,height:600,transparent:true,frame:false,webPreferences:{offscreen:true,backgroundThrottling:false,preload:path.join(__dirname,'renderer-menu-preload.cjs')}});
 const js=s=>w.webContents.executeJavaScript(s);
 const until=async s=>{for(let i=0;i<150;i++){if(await js(s))return;await delay(20);}throw Error('Timed out: '+s);};
 const move=async(x,y)=>{w.webContents.sendInputEvent({type:'mouseMove',x,y});await delay(280);};
 const shot=async name=>fs.writeFileSync(path.join(out,name+'.png'),(await w.webContents.capturePage()).toPNG());
 await w.loadFile(path.join(root,'index.html'));
 await until("typeof rayMenu.open==='function'");
 w.webContents.send('test:show',{sessionId:'neon-test',phase:'ready'});
 await delay(1000);
 await move(430,300);await shot('idle');
 await move(477,219);await shot('hover');
 assert(await js("$('centerDirection').classList.contains('is-active')"),'Pointer direction must activate over inner prompt');
 assert.equal(await js("getComputedStyle(halo,'::before').content"),'none');
 const fill=await js("getComputedStyle(rayMenu.shadowRoot.querySelector('.ray-menu-arc[data-hovered=\"true\"]')).fill");
 assert.equal(fill,'rgb(79, 250, 122)','Active arc uses flat green');
 assert.equal(await js("rayMenu.shadowRoot.querySelectorAll('.halo-active-edge').length"),0);
 const first=await js("$('centerDirection').style.getPropertyValue('--direction-angle')");
 await move(383,219);
 assert.notEqual(await js("$('centerDirection').style.getPropertyValue('--direction-angle')"),first,'Direction follows pointer');
 await move(477,219);
 w.webContents.sendInputEvent({type:'mouseDown',button:'left',clickCount:1,x:477,y:219});await delay(90);await shot('pressed');
 assert(await js("!!rayMenu.shadowRoot.querySelector('[data-pressed=\"true\"]')"),'Pointer down compresses selected sector');
 w.webContents.sendInputEvent({type:'mouseUp',button:'left',clickCount:1,x:477,y:219});await delay(280);
 assert.equal(inserts,1,'One click produces exactly one insertion request');
 assert(await js("rayMenu.isOpen"),'Failed insertion retains the ring');
 await js("notify('');toggleOuter()");await move(531,125);await shot('outer-hover');
 assert.equal(await js("outerRayMenu.shadowRoot.querySelectorAll('#halo-obsidian,#halo-jade,#halo-edge,.halo-active-edge').length"),0);
 await js("openEditor(prompts[0])");await delay(350);await shot('editor');
 assert(await js("!editor.hidden && document.activeElement.id==='titleInput'"));
 assert.equal(w.isVisible(),false,'QA must remain offscreen');
 fs.writeFileSync(path.join(out,'result.json'),JSON.stringify({ok:true,root,out,inserts,fill}));app.exit(0);
}).catch(e=>{console.error(e);console.error('ARTIFACTS '+out);app.exit(1);});
